    private static void put(String russian, String english) { EN.put(russian, english); }
    private KotCodeLanguage() {}

    public static String text(String russian) {
        if (russian == null) return "";
        if (!"en".equalsIgnoreCase(VisualConfig.get().language)) return russian;
        if (russian.startsWith("ФОРМА: ")) return "SHAPE: " + text(russian.substring("ФОРМА: ".length()));
        if (russian.startsWith("КРИТИЧЕСКИЕ ЧАСТИЦЫ: ")) return "CRITICAL PARTICLES: " + text(russian.substring("КРИТИЧЕСКИЕ ЧАСТИЦЫ: ".length()));
        if (russian.startsWith("РАДУЖНЫЙ ЦВЕТ: ")) return "RAINBOW COLOR: " + text(russian.substring("РАДУЖНЫЙ ЦВЕТ: ".length()));
        if (russian.startsWith("СТЕКЛЯННОЕ МЕНЮ: ")) return "GLASS MENU: " + text(russian.substring("СТЕКЛЯННОЕ МЕНЮ: ".length()));
        return EN.getOrDefault(russian, russian);
    }

    public static boolean isEnglish() { return "en".equalsIgnoreCase(VisualConfig.get().language); }
